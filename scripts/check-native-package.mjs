import {spawnSync} from 'node:child_process';
import {cpSync,mkdirSync,writeFileSync} from 'node:fs';
import {join,resolve,dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const [platformInput,toolchainInput,name='package',sketch='examples/Blink',board='stc32g12k128',...extra]=process.argv.slice(2);
if(!platformInput||!toolchainInput)throw new Error('Usage: node scripts/check-native-package.mjs <unpacked-platform> <native-toolchain> [name sketch board extra-cli-options...]');
const work=resolve(root,'.tmp/native-driver',name);
const user=join(work,'user');
mkdirSync(user,{recursive:true});
const installed=join(user,'hardware/stc/mcs251');
cpSync(resolve(platformInput),installed,{recursive:true});
const config=join(work,'arduino-cli.json');
writeFileSync(config,JSON.stringify({directories:{user,data:join(process.env.LOCALAPPDATA,'Arduino15')}},null,2));
const argv=['compile','--verbose','--config-file',config,'--fqbn',`stc:mcs251:${board}`,'--build-path',join(work,'build'),'--build-property',`runtime.tools.stcxx-toolchain.path=${resolve(toolchainInput)}`,...extra,resolve(root,sketch)];
const result=spawnSync('arduino-cli',argv,{encoding:'utf8',windowsHide:true,maxBuffer:128*1024*1024});
const log=(result.stdout||'')+(result.stderr||'');writeFileSync(work+'.log',log);
console.log(log.split(/\r?\n/).filter(l=>/^Sketch uses|^Global variables|: (?:fatal )?error[: ]|^stcxx:|^STCXX_NATIVE_LINK|^Error during/.test(l)).slice(-20).join('\n'));
if(/(?:powershell|python|stc-windows|stcxx-cli\.sh)/i.test(log))throw new Error('Legacy command appeared in native package log');
if(!log.includes('stcxx.exe')||!log.includes('clang.exe')||!log.includes('sdcc.exe'))throw new Error('Missing native compiler trace');
console.log(`status=${result.status} log=${work}.log`);
process.exit(result.status??1);
